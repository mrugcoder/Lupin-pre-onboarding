"""
Reports router — HR only.

Endpoints:
  GET /reports/export/excel  — stream full candidate list as .xlsx
  GET /reports/export/pdf    — stream funnel summary report as PDF
"""

import io
import logging
from datetime import datetime
from typing import Any, Dict, List

from fastapi import APIRouter, Depends
from fastapi.responses import StreamingResponse
from sqlalchemy import func
from sqlalchemy.orm import Session

from app.database import get_db
from app.dependencies import require_hr_role
from app.models.candidate import Candidate, CandidateStatus
from app.models.joining import JoiningRecord, JoiningStatus
from app.models.user import User

logger = logging.getLogger(__name__)

router = APIRouter(prefix="/reports", tags=["reports"], redirect_slashes=False)

FUNNEL_ORDER = [
    CandidateStatus.new_application.value,
    CandidateStatus.shortlisted.value,
    CandidateStatus.interview_scheduled.value,
    CandidateStatus.selected.value,
    CandidateStatus.rejected.value,
    CandidateStatus.hold.value,
    "Joined",
]


def _get_funnel_totals(db: Session) -> Dict[str, int]:
    status_rows = (
        db.query(Candidate.status, func.count(Candidate.id))
        .group_by(Candidate.status)
        .all()
    )
    totals: Dict[str, int] = {s: 0 for s in FUNNEL_ORDER}
    for status_val, cnt in status_rows:
        if status_val in totals:
            totals[status_val] = cnt
    totals["Joined"] = (
        db.query(func.count(JoiningRecord.id))
        .filter(JoiningRecord.status == JoiningStatus.joined.value)
        .scalar()
        or 0
    )
    return totals


# ---------------------------------------------------------------------------
# GET /reports/export/excel
# ---------------------------------------------------------------------------

@router.get(
    "/export/excel",
    summary="Export candidate list to Excel (HR only)",
    response_class=StreamingResponse,
)
def export_excel(
    db: Session = Depends(get_db),
    _: User = Depends(require_hr_role),
) -> StreamingResponse:
    import openpyxl
    from openpyxl.styles import Alignment, Font, PatternFill, Border, Side

    candidates = (
        db.query(Candidate).order_by(Candidate.created_at.desc()).all()
    )

    wb = openpyxl.Workbook()
    ws = wb.active
    ws.title = "Candidates"

    # ── Header styling ───────────────────────────────────────────────────────
    header_font = Font(name="Calibri", bold=True, color="FFFFFF", size=11)
    header_fill = PatternFill(start_color="0F2040", end_color="0F2040", fill_type="solid")
    header_align = Alignment(horizontal="center", vertical="center", wrap_text=True)
    thin = Side(style="thin", color="CCCCCC")
    border = Border(left=thin, right=thin, top=thin, bottom=thin)

    headers = [
        "Application ID",
        "Full Name",
        "Department",
        "Status",
        "Qualification",
        "Experience (yrs)",
        "Expected CTC (₹)",
        "Date Applied",
    ]
    col_widths = [18, 24, 20, 20, 20, 16, 16, 16]

    ws.row_dimensions[1].height = 30
    for col_idx, (header, width) in enumerate(zip(headers, col_widths), start=1):
        cell = ws.cell(row=1, column=col_idx, value=header)
        cell.font = header_font
        cell.fill = header_fill
        cell.alignment = header_align
        cell.border = border
        ws.column_dimensions[cell.column_letter].width = width

    # ── Data rows ────────────────────────────────────────────────────────────
    alt_fill = PatternFill(start_color="EAF1FB", end_color="EAF1FB", fill_type="solid")
    data_align = Alignment(vertical="center")

    for row_idx, c in enumerate(candidates, start=2):
        row_fill = alt_fill if row_idx % 2 == 0 else None
        applied_date = c.created_at.strftime("%d %b %Y") if c.created_at else ""
        exp_ctc = float(c.expected_ctc) if c.expected_ctc else ""
        years_exp = float(c.years_experience) if c.years_experience else ""

        row_data = [
            c.candidate_code,
            c.full_name,
            c.department_applied or "",
            c.status,
            c.qualification or "",
            years_exp,
            exp_ctc,
            applied_date,
        ]
        ws.row_dimensions[row_idx].height = 20
        for col_idx, value in enumerate(row_data, start=1):
            cell = ws.cell(row=row_idx, column=col_idx, value=value)
            cell.alignment = data_align
            cell.border = border
            if row_fill:
                cell.fill = row_fill

    # ── Freeze header ────────────────────────────────────────────────────────
    ws.freeze_panes = "A2"

    # Metadata sheet
    ws_meta = wb.create_sheet("Report Info")
    ws_meta["A1"] = "Generated by"
    ws_meta["B1"] = "Lupin Pre-Onboarding Connect"
    ws_meta["A2"] = "Generated at"
    ws_meta["B2"] = datetime.utcnow().strftime("%Y-%m-%d %H:%M UTC")
    ws_meta["A3"] = "Total candidates"
    ws_meta["B3"] = len(candidates)

    stream = io.BytesIO()
    wb.save(stream)
    stream.seek(0)

    timestamp = datetime.utcnow().strftime("%Y%m%d_%H%M")
    filename = f"lupin_candidates_{timestamp}.xlsx"

    logger.info("Excel export generated: %d candidates", len(candidates))

    return StreamingResponse(
        stream,
        media_type="application/vnd.openxmlformats-officedocument.spreadsheetml.sheet",
        headers={"Content-Disposition": f'attachment; filename="{filename}"'},
    )


